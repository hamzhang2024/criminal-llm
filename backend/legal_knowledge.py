import logging
from pathlib import Path

logger = logging.getLogger(__name__)

# ── 内置法律文件目录 ──
LEGAL_DB_DIR = Path(__file__).parent / "legal_db"

def _load_builtin_law(filename: str) -> str:
    """从 legal_db/ 加载内置法律文件"""
    law_path = LEGAL_DB_DIR / filename
    if not law_path.exists():
        logger.info(f"[法律知识库] 内置法律文件不存在: {filename}")
        return ""
    with open(law_path, encoding="utf-8") as f:
        return f.read()


def load_criminal_law() -> str:
    """加载刑法全文"""
    return _load_builtin_law("criminal_law.md")


def load_criminal_procedure_law() -> str:
    """加载刑诉法全文"""
    return _load_builtin_law("criminal_procedure_law.md")


def load_all_builtin_laws() -> str:
    """加载所有内置法律"""
    parts = []
    if not LEGAL_DB_DIR.exists():
        return ""
    for f in sorted(LEGAL_DB_DIR.glob("*.md")):
        try:
            with open(f, encoding="utf-8") as fh:
                content = fh.read()
                parts.append(content)
        except Exception as e:
            logger.error(f"[法律知识库] 加载 {f.name} 失败: {e}")
    return "\n\n".join(parts)


